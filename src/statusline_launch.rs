//! Command lines for Claude Code's `statusLine` on Windows (AH-211).
//!
//! Claude Code runs the command through Git Bash when it is installed and through PowerShell
//! otherwise, and a `statusLine` has no `args` or `shell` field, so the one string must mean
//! the same in both shells. Two readable forms qualify:
//! - a bare path to `aherald-cli.exe`, when no character in it is special to either shell;
//! - `powershell -File "<path>"`, where only a path used as an argument is quoted, so a space
//!   is fine; a path with `"`, `$` or a backtick still differs, as both shells expand them
//!   inside double quotes.
//!
//! Neither fits such a path, which keeps the encoded command of earlier versions.
use std::path::Path;

pub const COMPANION_NAME: &str = "aherald-cli.exe";
pub const SCRIPT_NAME: &str = "statusline.ps1";

/// Relays stdin to `aherald.exe --statusline` and its stdout back, byte for byte. PowerShell
/// neither waits for a GUI program nor collects its stdout unless piped, and `Out-String`
/// would re-encode UTF-8 and ANSI colours, so the bytes are copied by hand. The user's own
/// command is not named here: `aherald.exe` reads it from the setup receipt.
pub const SCRIPT_TEXT: &str = "\
# Generated by aherald --setup for Claude Code's statusLine. Removed by --unsetup.
$ErrorActionPreference = 'Stop'
# Process.Start initializes a text writer even though only its byte stream is used; a
# BOM-free encoding keeps that initialization from prefixing the payload.
[Console]::InputEncoding = [Text.UTF8Encoding]::new($false)
$start = [Diagnostics.ProcessStartInfo]::new()
$start.FileName = Join-Path $PSScriptRoot 'aherald.exe'
$start.Arguments = '--statusline'
$start.UseShellExecute = $false
$start.CreateNoWindow = $true
$start.RedirectStandardInput = $true
$start.RedirectStandardOutput = $true
$process = [Diagnostics.Process]::Start($start)
[Console]::OpenStandardInput().CopyTo($process.StandardInput.BaseStream)
$process.StandardInput.BaseStream.Close()
$process.StandardOutput.BaseStream.CopyTo([Console]::OpenStandardOutput())
$process.WaitForExit()
exit $process.ExitCode
";

fn forward_slashes(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Whether `command` is a `statusLine` command aHerald wrote, in any of its forms: a path to
/// aHerald followed by `--statusline`, or the relay script of this module. Setup uses it to
/// avoid nesting its own wrapper inside itself.
pub fn is_wrapper(command: &str) -> bool {
    let named =
        command.to_ascii_lowercase().contains("aherald") && command.contains(" --statusline");
    let script = command
        .starts_with("powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File \"")
        && command.ends_with(&format!("/{SCRIPT_NAME}\""));
    named || script
}

/// `<companion> --statusline` as a bare command, if the path needs no quoting in either shell.
pub fn companion_command(companion: &Path) -> Option<String> {
    let path = forward_slashes(companion);
    path.chars()
        // `~` is only special at the start of a word, which a drive path never has.
        .all(|c| c.is_alphanumeric() || matches!(c, '_' | '-' | '.' | '/' | ':' | '~'))
        .then(|| format!("{path} --statusline"))
}

/// `powershell -File "<script>"`, if both shells read the quoted path the same way.
pub fn script_command(script: &Path) -> Option<String> {
    let path = forward_slashes(script);
    (!path
        .chars()
        .any(|c| c.is_control() || matches!(c, '"' | '$' | '`')))
    .then(|| {
        format!("powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File \"{path}\"")
    })
}
